// never promise a charge here. Keys are category SLUGs (see prisma/seedCategories.ts).

export type CategoryFaq = { q: string; a: string }
export type CategorySeo = {
  keyword: string
  /**
   * Secondary terms appended to the <title>: „<keyword> — <titleTail> | მცოდნე".
   *
   * WHY: the title used to be the service NAME alone („საგადასახადო
   * კონსულტაცია"), which is what WE call it. SERP research on 2026-08-01 showed
   * Georgians search the PROBLEM instead — „დღგ", „დეკლარაცია", „ჯარიმა", „1%".
   * Those titles also ran only 27–33 characters, so roughly half the usable
   * width was empty. This puts the words people actually type into the one
   * element Google weighs most, without pushing past ~60.
   *
   * ⚠️ KEEP `keyword + ' — ' + titleTail + ' | მცოდნე'` UNDER 60 CHARACTERS.
   * Pinned by tests/categorySeo.test.ts.
   */
  titleTail: string
  /**
   * The <meta name="description">. MUST stay ≤160 characters.
   *
   * It exists because the page used to fall back to `intro`, which runs
   * 280–300 characters — Google cuts a snippet at roughly 160, so every
   * category page shipped a description that was truncated mid-sentence in the
   * results. A description is ad copy for the SERP, not the page's opening
   * paragraph; they have different jobs and different lengths.
   */
  metaDescription: string
  intro: string
  faq: CategoryFaq[]
}

