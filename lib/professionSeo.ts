// Profession-level SEO landing pages — /experts/<slug> (was /konsultacia/[slug]
// until stage 8, 2026-08-19; served by app/experts/[slug]/_profession.tsx, and
// the slug is resolved as a profession BEFORE an expert — see that page).
//
// WHY THIS EXISTS SEPARATELY FROM categorySeo:
// Georgian search splits into two different head terms for the same need.
//   • SPHERE terms — „საგადასახადო კონსულტაცია" → were served by /categories/tax
//     (retired stage 8; that URL 308s to /experts?category=tax)
//   • PROFESSION terms — „ბუღალტერთან კონსულტაცია" → served by this route
// They are not synonyms to a search engine and a single page cannot own both,
// so each gets its own URL, H1 and body copy. The two are cross-linked, and the
// profession page is written around the PERSON (what this specialist does, when
// you go to one, how to pick) while the category page is written around the
// SPHERE (what the field covers) — that difference is what keeps this from
// being a doorway set.
//
// SUPPLY: a profession may legitimately have zero experts today (the catalog is
// filling in gradually). The page then shows the same honest empty state the
// category pages use — it never implies supply that isn't there.
//
// HONESTY RULES (same as categorySeo): no invented stats, no rankings, no
// promises of a charge while payments are off. Only truths — ხელით
// შერჩეული ექსპერტები, ფასს ექსპერტი ადგენს და წინასწარ ჩანს.

import type { CategoryFaq } from './categorySeo'

export type ProfessionSeo = {
  /** URL segment: /experts/<slug>. Latin, matches the category slug style.
   *  ⚠️ Reserved in lib/expertSlug so no expert profile can be minted onto it. */
  slug: string
  /** The exact head term this page targets. Used in <title>, H1 and anchors. */
  keyword: string
  /** Short label, NOMINATIVE — for chips and link strips („ბუღალტერი"). */
  label: string
  /**
   * Georgian declines by stem change, not by suffixing: „ბუღალტერი" + „თან"
   * gives the non-word „ბუღალტერითან", and + „ები" gives „ბუღალტერიები".
   * The -ი drops (and some stems syncopate: ბუღალტერი → ბუღალტრები), so both
   * inflected forms are written out per profession rather than derived.
   */
  /** Adverbial/-თან form: „ბუღალტერთან". */
  labelWith: string
  /** Plural nominative: „ბუღალტრები". */
  labelPlural: string
  /** Category slug whose experts this page lists. MUST be a live category. */
  categorySlug: string
  /** Meta description + lead paragraph (kept under ~160 chars for the meta). */
  metaDescription: string
  intro: string
  /** „როდის ღირს მიმართვა" — concrete situations, not benefits fluff. */
  when: string[]
  faq: CategoryFaq[]
}

