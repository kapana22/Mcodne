async function main() {
  const publish = process.argv.includes('--publish')
  const status = publish ? 'PUBLISHED' : 'DRAFT'
  const now = new Date()

  for (const p of POSTS) {
    const existing = await prisma.post.findUnique({ where: { slug: p.slug }, select: { publishedAt: true } })
    await prisma.post.upsert({
      where: { slug: p.slug },
      create: {
        slug: p.slug,
        title: p.title,
        excerpt: p.excerpt,
        body: p.body,
        tag: p.tag,
        status,
        authorName: 'მცოდნე',
        publishedAt: publish ? now : null,
      },
      update: {
        title: p.title,
        excerpt: p.excerpt,
        body: p.body,
        tag: p.tag,
        status,
        // Keep the ORIGINAL publish date on re-runs — re-seeding an edit must not
        // reorder the blog or churn the sitemap's lastModified.
        publishedAt: publish ? (existing?.publishedAt ?? now) : existing?.publishedAt ?? null,
      },
    })
    console.log(`${existing ? 'updated' : 'created'}  ${status.padEnd(9)} /blog/${p.slug}`)
  }

  console.log(`\n${POSTS.length} posts seeded as ${status}.`)
  if (!publish) console.log('Review them in the admin „ბლოგი“ tab, then publish there or re-run with --publish.')
}

main()
  .catch((e) => {
    console.error(e)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
